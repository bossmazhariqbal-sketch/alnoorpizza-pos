CREATE TABLE IF NOT EXISTS public.membership_cards (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 120),
  phone_number text NOT NULL CHECK (char_length(btrim(phone_number)) BETWEEN 1 AND 30),
  card_number text NOT NULL CHECK (char_length(btrim(card_number)) BETWEEN 1 AND 80),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT membership_cards_card_number_key UNIQUE (card_number)
);

ALTER TABLE public.membership_cards
  ADD COLUMN IF NOT EXISTS phone_number text NOT NULL DEFAULT '';

ALTER TABLE public.membership_cards ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.membership_cards TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.membership_cards_id_seq TO authenticated;

DROP POLICY IF EXISTS membership_cards_authenticated_all ON public.membership_cards;
CREATE POLICY membership_cards_authenticated_all
  ON public.membership_cards
  FOR ALL
  TO authenticated
  USING (true)
  WITH CHECK (true);
